import { timingSafeEqual } from 'node:crypto';
import type { Request, Response, RequestHandler } from 'express';

/**
 * The privileged renderer origin. Only this origin may accompany state-changing
 * desktop API requests; it exists because the renderer is served from the
 * custom fmd2:// scheme, never from a random loopback port.
 */
export const DESKTOP_TRUSTED_ORIGIN = 'fmd2://studio';

/** Header carrying the per-launch capability token. Header-only by contract: never a query parameter. */
export const LAUNCH_TOKEN_HEADER = 'x-fmd2-launch';

export interface DesktopAuthOptions {
  /** Per-launch capability token generated by the Electron main process. */
  launchToken: string;
  /** Trusted renderer origin. Defaults to the privileged fmd2://studio scheme. */
  trustedOrigin?: string;
}

function safeEqual(a: string, b: string): boolean {
  const left = Buffer.from(a, 'utf8');
  const right = Buffer.from(b, 'utf8');
  if (left.length !== right.length) return false;
  return timingSafeEqual(left, right);
}

function isLoopbackHost(host: string): boolean {
  return host.startsWith('127.0.0.1:');
}

/**
 * Desktop boundary middleware for /api routes:
 * - every request must arrive on a loopback Host (127.0.0.1:<port>);
 * - state-changing methods additionally require the studio Origin and the
 *   per-launch token, compared constant-time;
 * - rejections happen before any route handler runs.
 *
 * Loopback is a network boundary, not user authentication.
 */
export function desktopAuth(options: DesktopAuthOptions): RequestHandler {
  const trustedOrigin = options.trustedOrigin ?? DESKTOP_TRUSTED_ORIGIN;
  return (req: Request, res: Response, next: () => void) => {
    const host = req.headers.host || '';
    if (!isLoopbackHost(host)) {
      res.status(403).json({ error: 'Forbidden host.' });
      return;
    }

    const method = req.method.toUpperCase();
    if (method === 'GET' || method === 'HEAD' || method === 'OPTIONS') {
      next();
      return;
    }

    const origin = req.headers.origin || '';
    if (origin !== trustedOrigin) {
      res.status(403).json({ error: 'Forbidden origin.' });
      return;
    }

    const provided = req.headers[LAUNCH_TOKEN_HEADER];
    if (typeof provided !== 'string' || !safeEqual(provided, options.launchToken)) {
      res.status(403).json({ error: 'Forbidden.' });
      return;
    }

    next();
  };
}
